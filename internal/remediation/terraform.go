package remediation

import (
	"fmt"
	"strings"
	"time"
)

type TerraformGenerator struct {
	customerID string
}

type RemediationAction struct {
	Type        string            `json:"type"`
	ResourceID  string            `json:"resource_id"`
	Action      string            `json:"action"`
	Parameters  map[string]string `json:"parameters"`
	EstSavings  float64           `json:"estimated_savings"`
	Risk        string            `json:"risk"`
}

func NewTerraformGenerator(customerID string) *TerraformGenerator {
	return &TerraformGenerator{customerID: customerID}
}

func (t *TerraformGenerator) GenerateInstanceRightSizing(instanceID, currentType, recommendedType string, monthlySavings float64) string {
	template := `# Generated by Yukti FinOps - Instance Right-sizing
# Customer: %s
# Generated: %s
# Estimated Monthly Savings: $%.2f

terraform {
  required_providers {
    aws = {
      source  = "hashicorp/aws"
      version = "~> 5.0"
    }
  }
}

# Right-size EC2 instance from %s to %s
resource "aws_instance" "optimized_%s" {
  # Current instance: %s
  instance_type = "%s"
  
  # Copy configuration from existing instance
  ami                    = data.aws_instance.current.ami
  key_name              = data.aws_instance.current.key_name
  vpc_security_group_ids = data.aws_instance.current.vpc_security_group_ids
  subnet_id             = data.aws_instance.current.subnet_id
  
  # Preserve tags
  tags = merge(
    data.aws_instance.current.tags,
    {
      "OptimizedBy" = "Yukti-FinOps"
      "OriginalType" = "%s"
      "OptimizedDate" = "%s"
    }
  )
  
  lifecycle {
    create_before_destroy = true
  }
}

# Data source for current instance
data "aws_instance" "current" {
  instance_id = "%s"
}

# Output the new instance details
output "optimized_instance_id" {
  value = aws_instance.optimized_%s.id
}

output "estimated_monthly_savings" {
  value = "%.2f"
}

# IMPORTANT: Review this configuration before applying
# 1. Verify the instance type change is appropriate
# 2. Test in non-production environment first
# 3. Schedule maintenance window for production changes
# 4. Backup any critical data before proceeding
`

	return fmt.Sprintf(template,
		t.customerID,
		time.Now().Format("2006-01-02 15:04:05"),
		monthlySavings,
		currentType, recommendedType,
		strings.ReplaceAll(instanceID, "-", "_"),
		instanceID,
		recommendedType,
		currentType,
		time.Now().Format("2006-01-02"),
		instanceID,
		strings.ReplaceAll(instanceID, "-", "_"),
		monthlySavings,
	)
}

