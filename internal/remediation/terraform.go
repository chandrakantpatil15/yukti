func (t *TerraformGenerator) GenerateCloudFormationTemplate(action RemediationAction) string {
	switch action.Type {
	case "rightsizing":
		return t.generateCFRightSizing(action)
	case "termination":
		return t.generateCFTermination(action)
	default:
		return "# Unsupported action type for CloudFormation"
	}
}

func (t *TerraformGenerator) generateCFRightSizing(action RemediationAction) string {
	template := `AWSTemplateFormatVersion: '2010-09-09'
Description: 'Yukti FinOps - EC2 Instance Right-sizing'

Parameters:
  InstanceId:
    Type: String
    Default: '%s'
    Description: 'Instance ID to optimize'
  
  NewInstanceType:
    Type: String
    Default: '%s'
    Description: 'Recommended instance type'

Resources:
  OptimizedInstance:
    Type: AWS::EC2::Instance
    Properties:
      InstanceType: !Ref NewInstanceType
      ImageId: !GetAtt CurrentInstance.ImageId
      KeyName: !GetAtt CurrentInstance.KeyName
      SecurityGroupIds: !GetAtt CurrentInstance.SecurityGroupIds
      SubnetId: !GetAtt CurrentInstance.SubnetId
      Tags:
        - Key: OptimizedBy
          Value: Yukti-FinOps
        - Key: OriginalType
          Value: !GetAtt CurrentInstance.InstanceType
        - Key: EstimatedSavings
          Value: '%.2f'

Outputs:
  NewInstanceId:
    Description: 'Optimized instance ID'
    Value: !Ref OptimizedInstance
  
  EstimatedMonthlySavings:
    Description: 'Estimated monthly savings'
    Value: '%.2f'
`

	return fmt.Sprintf(template,
		action.ResourceID,
		action.Parameters["recommended_type"],
		action.EstSavings,
		action.EstSavings,
	)
}

func (t *TerraformGenerator) generateCFTermination(action RemediationAction) string {
	template := `AWSTemplateFormatVersion: '2010-09-09'
Description: 'Yukti FinOps - EC2 Instance Termination'

Parameters:
  InstanceId:
    Type: String
    Default: '%s'
    Description: 'Instance ID to terminate'

Resources:
  TerminationLambda:
    Type: AWS::Lambda::Function
    Properties:
      FunctionName: !Sub 'yukti-terminate-${InstanceId}'
      Runtime: python3.9
      Handler: index.handler
      Code:
        ZipFile: |
          import boto3
          import json
          
          def handler(event, context):
              ec2 = boto3.client('ec2')
              instance_id = event['InstanceId']
              
              try:
                  response = ec2.terminate_instances(InstanceIds=[instance_id])
                  return {
                      'statusCode': 200,
                      'body': json.dumps(f'Instance {instance_id} terminated successfully')
                  }
              except Exception as e:
                  return {
                      'statusCode': 500,
                      'body': json.dumps(f'Error: {str(e)}')
                  }
      Role: !GetAtt LambdaExecutionRole.Arn

  LambdaExecutionRole:
    Type: AWS::IAM::Role
    Properties:
      AssumeRolePolicyDocument:
        Version: '2012-10-17'
        Statement:
          - Effect: Allow
            Principal:
              Service: lambda.amazonaws.com
            Action: sts:AssumeRole
      ManagedPolicyArns:
        - arn:aws:iam::aws:policy/service-role/AWSLambdaBasicExecutionRole
      Policies:
        - PolicyName: EC2TerminatePolicy
          PolicyDocument:
            Version: '2012-10-17'
            Statement:
              - Effect: Allow
                Action:
                  - ec2:TerminateInstances
                Resource: '*'

Outputs:
  LambdaFunctionArn:
    Description: 'Lambda function for termination'
    Value: !GetAtt TerminationLambda.Arn
  
  EstimatedMonthlySavings:
    Description: 'Estimated monthly savings'
    Value: '%.2f'
`

	return fmt.Sprintf(template, action.ResourceID, action.EstSavings)
}