package iac

import (
	"fmt"
	"strings"
	"time"
)

// TerraformGenerator generates Terraform scripts for AWS optimizations
type TerraformGenerator struct {
	provider string
	region   string
}

// NewTerraformGenerator creates a new Terraform generator
func NewTerraformGenerator(provider, region string) *TerraformGenerator {
	return &TerraformGenerator{
		provider: provider,
		region:   region,
	}
}

// GenerateEC2Optimization generates Terraform for EC2 instance optimization
func (tg *TerraformGenerator) GenerateEC2Optimization(recommendation *OptimizationRecommendation) *IaCScript {
	var terraformCode strings.Builder
	
	// Provider configuration
	terraformCode.WriteString(fmt.Sprintf(`# Generated by Yukti FinOps - %s
# Recommendation: %s
# Estimated Savings: $%.2f

terraform {
  required_providers {
    aws = {
      source  = "hashicorp/aws"
      version = "~> 5.0"
    }
  }
}

provider "aws" {
  region = "%s"
}

`, time.Now().Format("2006-01-02 15:04:05"), recommendation.Action, recommendation.EstimatedSavings, tg.region))

	switch recommendation.Action {
	case "downsize":
		terraformCode.WriteString(tg.generateDownsizeScript(recommendation))
	case "terminate":
		terraformCode.WriteString(tg.generateTerminateScript(recommendation))
	case "schedule":
		terraformCode.WriteString(tg.generateScheduleScript(recommendation))
	case "spot_conversion":
		terraformCode.WriteString(tg.generateSpotConversionScript(recommendation))
	}

	// Add rollback script
	rollbackCode := tg.generateRollbackScript(recommendation)

	return &IaCScript{
		ID:               fmt.Sprintf("tf-%s-%d", recommendation.ResourceID, time.Now().Unix()),
		Type:             "terraform",
		Provider:         "aws",
		Action:           recommendation.Action,
		ResourceID:       recommendation.ResourceID,
		Code:             terraformCode.String(),
		RollbackCode:     rollbackCode,
		EstimatedSavings: recommendation.EstimatedSavings,
		GeneratedAt:      time.Now(),
		Instructions:     tg.generateInstructions(recommendation),
	}
}

// generateDownsizeScript generates Terraform for instance downsizing
func (tg *TerraformGenerator) generateDownsizeScript(rec *OptimizationRecommendation) string {
	return fmt.Sprintf(`# Downsize EC2 instance for cost optimization
data "aws_instance" "target" {
  instance_id = "%s"
}

# Stop instance before resizing
resource "aws_ec2_instance_state" "stop_instance" {
  instance_id = data.aws_instance.target.id
  state       = "stopped"
}

# Modify instance type
resource "aws_instance" "optimized" {
  ami           = data.aws_instance.target.ami
  instance_type = "%s"  # Recommended smaller instance type
  
  # Preserve existing configuration
  key_name               = data.aws_instance.target.key_name
  vpc_security_group_ids = data.aws_instance.target.vpc_security_group_ids
  subnet_id              = data.aws_instance.target.subnet_id
  
  # Preserve tags
  tags = data.aws_instance.target.tags
  
  # Replace the existing instance
  replace_triggered_by = [aws_ec2_instance_state.stop_instance]
}

output "old_instance_type" {
  value = data.aws_instance.target.instance_type
}

output "new_instance_type" {
  value = aws_instance.optimized.instance_type
}

output "estimated_monthly_savings" {
  value = "%.2f USD"
}
`, rec.ResourceID, rec.RecommendedInstanceType, rec.EstimatedSavings*30)
}

