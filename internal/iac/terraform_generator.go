// generateScheduleScript generates Terraform for instance scheduling
func (tg *TerraformGenerator) generateScheduleScript(rec *OptimizationRecommendation) string {
	return fmt.Sprintf(`# Schedule EC2 instance for cost optimization
data "aws_instance" "target" {
  instance_id = "%s"
}

# Lambda function for instance scheduling
resource "aws_lambda_function" "scheduler" {
  filename         = "scheduler.zip"
  function_name    = "ec2-scheduler-${data.aws_instance.target.id}"
  role            = aws_iam_role.scheduler_role.arn
  handler         = "index.handler"
  runtime         = "python3.9"
  
  environment {
    variables = {
      INSTANCE_ID = data.aws_instance.target.id
    }
  }
}

# IAM role for Lambda
resource "aws_iam_role" "scheduler_role" {
  name = "ec2-scheduler-role-${data.aws_instance.target.id}"
  
  assume_role_policy = jsonencode({
    Version = "2012-10-17"
    Statement = [
      {
        Action = "sts:AssumeRole"
        Effect = "Allow"
        Principal = {
          Service = "lambda.amazonaws.com"
        }
      }
    ]
  })
}

# CloudWatch Events for scheduling
resource "aws_cloudwatch_event_rule" "stop_schedule" {
  name                = "stop-${data.aws_instance.target.id}"
  description         = "Stop instance at 6 PM"
  schedule_expression = "cron(0 18 * * ? *)"  # 6 PM daily
}

resource "aws_cloudwatch_event_rule" "start_schedule" {
  name                = "start-${data.aws_instance.target.id}"
  description         = "Start instance at 8 AM"
  schedule_expression = "cron(0 8 * * ? *)"   # 8 AM daily
}

output "estimated_monthly_savings" {
  value = "%.2f USD (58%% uptime reduction)"
}
`, rec.ResourceID, rec.EstimatedSavings*30)
}

// generateSpotConversionScript generates Terraform for Spot instance conversion
